"""Generate a pack's LaTeX package (e.g. mylab.sty) from its math assets.

The package provides, for prefix P (pack.yaml `latex.prefix`):
    \\Passet[k=v,...]{name}   the math body of math/<name>.tex, usable inside equation/align (\\label works)
    \\Pparam{k}               a parameter's value (used inside assets)
    \\Pdefaults{k=v,...}      parameter defaults (used inside assets)
and loads the pack's macros file (the shared notation). Macros only: no fonts, layout or page
settings. Needs LaTeX 2022-06 or newer; loads amsmath.

By default the package is written to <pack>/latex/ and points at the pack with an absolute path
(regenerate after moving it). With a bundle directory it writes a self-contained copy (package +
math files) whose paths are relative to the paper's main file, for Overleaf or a paper repo.
"""
from __future__ import annotations

import datetime
import pathlib
import shutil

from . import packs as packs_mod

TEMPLATE = r"""%% {prefix}.sty: {name} math assets for LaTeX.
%% Generated by doc-kit (doc-kit sty) from the {pack} pack. Do not edit; edit the .tex assets.
\NeedsTeXFormat{{LaTeX2e}}[2022-06-01]
\ProvidesExplPackage{{{prefix}}}{{{date}}}{{1.0}}{{{name} math assets (doc-kit)}}
\RequirePackage{{amsmath}}
\tl_new:N \g__{prefix}_root_tl
\tl_gset:Nn \g__{prefix}_root_tl {{{root}}}
\keys_define:nn {{ {prefix} }}
  {{ root .code:n = \tl_gset:Nx \g__{prefix}_root_tl {{ \tl_to_str:n {{#1}} }} }}
\ProcessKeyOptions [ {prefix} ]
\prop_new:N \l__{prefix}_params_prop
\cs_new_protected:Npn \__{prefix}_put:nn #1#2 {{ \prop_put:Nnn \l__{prefix}_params_prop {{#1}} {{#2}} }}
\cs_new_protected:Npn \__{prefix}_put_flag:n #1 {{ \__{prefix}_put:nn {{#1}} {{ true }} }}
\cs_new_protected:Npn \__{prefix}_default:nn #1#2
  {{ \prop_if_in:NnF \l__{prefix}_params_prop {{#1}} {{ \prop_put:Nnn \l__{prefix}_params_prop {{#1}} {{#2}} }} }}
\cs_new_protected:Npn \__{prefix}_default_flag:n #1 {{ \__{prefix}_default:nn {{#1}} {{ true }} }}
% \{prefix}asset[k=v]{{name}}: parameters are local to the asset (and inherited by nested assets).
\NewDocumentCommand \{prefix}asset {{ O{{}} m }}
  {{
    \group_begin:
      \keyval_parse:nnn \__{prefix}_put_flag:n \__{prefix}_put:nn {{#1}}
      \file_input:n {{ \g__{prefix}_root_tl {math}/ #2 .tex }}
    \group_end:
  }}
\NewDocumentCommand \{prefix}defaults {{ m }}
  {{ \keyval_parse:nnn \__{prefix}_default_flag:n \__{prefix}_default:nn {{#1}} }}
\NewExpandableDocumentCommand \{prefix}param {{ m }}
  {{ \prop_item:Nn \l__{prefix}_params_prop {{#1}} }}
\cs_new_protected:Npn \__{prefix}_input_macros: {{ \file_input:n {{ \g__{prefix}_root_tl {macros} }} }}
\ExplSyntaxOff
% The shared notation, read with normal catcodes.
\csname __{prefix}_input_macros:\endcsname
\endinput
"""


def build_sty(pack_dir, bundle=None, root=None) -> pathlib.Path:
    pack_dir = pathlib.Path(pack_dir).resolve()
    cfg = packs_mod.load_config(pack_dir)
    prefix = (cfg.get("latex") or {}).get("prefix")
    if not prefix or not prefix.isalpha():
        raise ValueError(f"{pack_dir.name}: pack.yaml needs latex.prefix (letters only, it becomes \\<prefix>asset)")
    math_dir = cfg.get("math", "math")
    macros = cfg.get("macros", f"{math_dir}/macros.tex")
    if bundle:
        out_dir = pathlib.Path(bundle).resolve()
        out_dir.mkdir(parents=True, exist_ok=True)
        shutil.copytree(pack_dir / math_dir, out_dir / math_dir, dirs_exist_ok=True)
        # TeX resolves \input against the directory it runs in (the paper's main file),
        # so a bundle placed next to the main file is found as "<dirname>/".
        root = root or out_dir.name + "/"
    else:
        out_dir = pack_dir / "latex"
        out_dir.mkdir(exist_ok=True)
        root = root or pack_dir.as_posix() + "/"
    text = TEMPLATE.format(prefix=prefix, pack=pack_dir.name, name=cfg.get("name", pack_dir.name),
                           date=datetime.date.today().strftime("%Y-%m-%d"), root=root, math=math_dir, macros=macros)
    out = out_dir / f"{prefix}.sty"
    out.write_text(text)
    return out
